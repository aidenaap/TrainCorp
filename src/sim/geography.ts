export function boundsOf(poly: Poly, pad = 0): Bounds {
  let minX = Infinity;
  let minY = Infinity;
  let maxX = -Infinity;
  let maxY = -Infinity;
  for (const [x, y] of poly) {
    if (x < minX) minX = x;
    if (y < minY) minY = y;
    if (x > maxX) maxX = x;
    if (y > maxY) maxY = y;
  }
  return { minX: minX - pad, minY: minY - pad, maxX: maxX + pad, maxY: maxY + pad };
}

const land = (
  id: string,
  minZoom: number,
  outlineDegrees: LonLat[],
  ice = false,
): LandMass => {
  const outline = projectPath(outlineDegrees);
  return { id, minZoom, outline, ice, bounds: boundsOf(outline) };
};

