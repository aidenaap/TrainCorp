/**
 * World geography for the map background.
 *
 * All shapes are authored as [lon, lat] degree pairs and projected once at module
 * load, so the data stays human-editable while the renderer only ever sees world
 * units. Resolution is deliberately coarse (~1-3 degrees) — enough for continents
 * to be instantly recognisable at a glance, cheap enough to re-trace every frame.
 *
 * Nothing here is copied from another game; the outlines are hand-simplified from
 * public-domain coastline geometry.
 */

import { projectPath, UNITS_PER_DEGREE, type LonLat, type Poly } from './projection';

export interface Bounds {
  minX: number;
  minY: number;
  maxX: number;
  maxY: number;
}

export interface LandMass {
  id: string;
  /** Larger landmasses keep their coastline stroke at low zoom; islets fade out. */
  minZoom: number;
  outline: Poly;
  /** Permanent ice sheet — painted pale instead of olive. */
  ice?: boolean;
  /** Precomputed so the renderer can cull offscreen shapes without touching points. */
  bounds: Bounds;
}

export interface MountainRange {
  id: string;
  name: string;
  /** 0..1 — drives ridge width, brightness and whether snow caps are drawn. */
  elevation: number;
  /** Half-width of the range in world units. */
  spread: number;
  /** Ridge centreline, not a closed polygon. */
  path: Poly;
  bounds: Bounds;
}

