const range = (
  id: string,
  name: string,
  elevation: number,
  spreadDegrees: number,
  pathDegrees: LonLat[],
): MountainRange => {
  const projected = projectPath(pathDegrees);
  const spread = spreadDegrees * UNITS_PER_DEGREE;
  return { id, name, elevation, spread, path: projected, bounds: boundsOf(projected, spread * 2) };
};

